<script>
    let swiperThumbs, swiperPreview;

    function initProductModalSwiper() {

        if (swiperThumbs) return; // avoid double init

        swiperThumbs = new Swiper(".product__media--nav", {
            loop: true,
            spaceBetween: 10,
            slidesPerView: 4,
            freeMode: true,
            watchSlidesProgress: true,
            slideToClickedSlide: true,
            breakpoints: {
                0:   { slidesPerView: 1 },
                200: { slidesPerView: 3 },
                480: { slidesPerView: 4 },
            },
            navigation: {
                nextEl: ".swiper-button-next",
                prevEl: ".swiper-button-prev",
            },
        });

        swiperPreview = new Swiper(".product__media--preview", {
            loop: false,   // 🔥 IMPORTANT
            spaceBetween: 10,
            thumbs: {
                swiper: swiperThumbs,
            },
        });
    }

    // modal open hone ke baad init karo
    $('#addToCart').on('shown.bs.modal', function () {
        initProductModalSwiper();
        swiperThumbs.update();
        swiperPreview.update();
    });
</script>

       
